// ---------------------------------------------------------------------------
// Helpers used by both server and client
// ---------------------------------------------------------------------------

export const API = {
  health: "/api/health",
  meta: "/api/meta",
  games: "/api/games",
  game: (id: string) => `/api/games/${id}`,
  commands: (id: string) => `/api/games/${id}/commands`,
  save: (id: string) => `/api/games/${id}/save`,
  export: (id: string) => `/api/games/${id}/export`,
  import: "/api/games/import",
  ws: (id: string) => `/api/ws?game=${encodeURIComponent(id)}`,
} as const;

export interface ApiError {
  error: string;
}

/** Generic JSON fetch helper. */
export async function apiFetch<T>(url: string, init?: RequestInit): Promise<T> {
  const res = await fetch(url, {
    headers: { "Content-Type": "application/json" },
    ...init,
  });
  if (!res.ok) {
    const body = (await res.json().catch(() => null)) as ApiError | null;
    throw new Error(body?.error ?? `HTTP ${res.status}`);
  }
  return (await res.json()) as T;
}

/** Helper to send a command. */
export function sendCommand(gameId: string, command: Command): Promise<CommandResult> {
  return apiFetch<CommandResult>(API.commands(gameId), {
    method: "POST",
    body: JSON.stringify(command),
  });
}

/** Clamp a value to a range. */
export function clamp(v: number, lo: number, hi: number): number {
  return Math.min(hi, Math.max(lo, v));
}

/** Format money compactly, e.g. $1.24M. */
export function fmtMoney(v: number): string {
  const abs = Math.abs(v);
  const sign = v < 0 ? "-" : "";
  if (abs >= 1_000_000) return `${sign}$${(abs / 1_000_000).toFixed(2)}M`;
  if (abs >= 10_000) return `${sign}$${(abs / 1_000).toFixed(1)}K`;
  return `${sign}$${Math.round(abs).toLocaleString("en-US")}`;
}

export function fmtNumber(v: number): string {
  return Math.round(v).toLocaleString("en-US");
}

export function distanceKm(a: Vec2, b: Vec2): number {
  return Math.hypot(a.x - b.x, a.y - b.y);
}
